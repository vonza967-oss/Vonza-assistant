const commonForbiddenClaims = [
  /\bfree\b/i,
  /\bguarantee(?:d)?\b.{0,30}\b(result|appointment|availability|price)\b/i,
  /\b(?:open|available).{0,20}24\/7|24\/7.{0,20}(?:open|available|emergency)\b/i,
  /\bwalk-?ins? (?:are )?(?:available|guaranteed|welcome)\b/i,
  /\bconfirmed for\b/i,
  /\bwe accept all insurance\b/i,
  /\bSmileCo\b.*\b(?:worse|better|cheaper)\b/i,
  /\bAspen\b.*\b(?:worse|better|cheaper)\b/i,
];

function buildExpectations(overrides = {}) {
  return {
    required: overrides.required || [],
    requiredAny: overrides.requiredAny || [],
    forbidden: [...commonForbiddenClaims, ...(overrides.forbidden || [])],
    followUpRequired: overrides.followUpRequired === true,
    followUpTurnIndexes: overrides.followUpTurnIndexes || [],
    followUpPattern: overrides.followUpPattern || /\b(book|schedule|appointment|leave|share|email|phone|contact|follow|which|what|when|details?)\b/i,
    leadCaptureExpected: overrides.leadCaptureExpected === true,
    handoffExpected: overrides.handoffExpected === true,
    handoffPattern: overrides.handoffPattern || /\b(emergency services|urgent care|team can follow up|leave your details|human|owner|office|clinic)\b/i,
    unsupported: overrides.unsupported === true,
    maxWords: overrides.maxWords || 80,
  };
}

